// Generates src/node/markdown/plugins/mermaidMetrics.ts: the advance widths
// mermaid diagrams are laid out with at build time. pele (the renderer)
// sizes labels from a width table when no canvas is available, and its
// built-in table is Arial's. The default theme renders diagrams in Inter,
// which runs about 8% wider at text sizes, so labels measured as Arial
// overflow their nodes. This measures the Inter subsets the theme ships, in
// Chromium, at a text size - Inter is a variable font whose optical-size
// axis makes its glyphs wider at 16px than at display sizes.
//
// Usage: node scripts/genMermaidMetrics.ts (needs the playwright-chromium
// browser, as the e2e tests do)

import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

import { chromium } from 'playwright-chromium'

const ROOT = path.resolve(import.meta.dirname, '..')
const FONTS = path.join(ROOT, 'src/client/theme-default/fonts')
const OUT = path.join(ROOT, 'src/node/markdown/plugins/mermaidMetrics.ts')
const SIZE = 16

const browser = await chromium.launch()
try {
  const page = await browser.newPage()
  await page.route('**/fonts/*.woff2', (route) =>
    route.fulfill({
      body: readFileSync(
        path.join(FONTS, path.basename(route.request().url()))
      ),
      contentType: 'font/woff2'
    })
  )
  await page.route('http://vitepress.test/', (route) =>
    route.fulfill({
      contentType: 'text/html',
      body: `<!doctype html><style>
@font-face{font-family:Inter;font-style:normal;font-weight:100 900;src:url(/fonts/inter-roman-latin.woff2) format('woff2')}
</style><span style="font-family:Inter">Inter <b>Inter</b></span>`
    })
  )
  await page.goto('http://vitepress.test/')
  const tables = await page.evaluate(async (size) => {
    // runs in the browser, which this project's types don't cover
    const doc: any = (globalThis as any).document
    await doc.fonts.load(`${size}px Inter`, 'a')
    await doc.fonts.load(`bold ${size}px Inter`, 'a')
    const ctx = doc.createElement('canvas').getContext('2d')
    const measure = (font: string) => {
      ctx.font = font
      let packed = ''
      for (let c = 32; c < 127; c++) {
        const em = (ctx.measureText(String.fromCharCode(c)).width / size) * 1000
        packed += Math.round(em).toString(36).padStart(2, '0')
      }
      return packed
    }
    return {
      regular: measure(`${size}px Inter`),
      bold: measure(`bold ${size}px Inter`)
    }
  }, SIZE)

  writeFileSync(
    OUT,
    `// Generated by scripts/genMermaidMetrics.ts - do not edit.
//
// Advance widths of printable ASCII in Inter, the default theme's font, as
// thousandths of an em, two base-36 digits each, measured in Chromium at
// ${SIZE}px from the subsets in src/client/theme-default/fonts.
export const INTER_REGULAR =
  '${tables.regular}'
export const INTER_BOLD =
  '${tables.bold}'
`
  )
  console.log(`wrote ${path.relative(ROOT, OUT)}`)
} finally {
  await browser.close()
}
